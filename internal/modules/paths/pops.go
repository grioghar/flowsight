// Where a router says it is.
//
// Carriers name their routers after the site that holds them. Lumen writes
// ae10.edge1.dal2.sp.lumen.tech; Microsoft writes po1.owr03.lax31.ntwk.msn.net;
// AT&T writes 172-11-154-1.lightspeed.tpkaks.sbcglobal.net. In each the site
// is an airport code or a city abbreviation, and reading it gives a better
// answer than an address database does, because a database places carrier
// equipment wherever the block was registered. A Microsoft router in Los
// Angeles sits in a range registered to RIPE, and the database duly puts it
// in London.
//
// This is an inference, not a measurement, and it is wrong sometimes: codes
// are reused, and a name can outlive a move. It is recorded as coming from
// the name so a reader can weigh it, and the latency check still applies.
// What it is not allowed to do is invent precision: the answer is a city,
// never a building.

// pop maps a site code to the city it names.
